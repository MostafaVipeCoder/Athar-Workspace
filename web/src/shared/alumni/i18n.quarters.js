/** `{ a: { b: 'x' } }` -> `{ 'a.b': 'x' }` (the registry is flat). */
function flat(o, prefix = '', out = {}) {
  for (const [k, v] of Object.entries(o)) {
    if (v && typeof v === 'object') flat(v, `${prefix}${k}.`, out)
    else out[`${prefix}${k}`] = v
  }
  return out
}

