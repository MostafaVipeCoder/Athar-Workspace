const CATEGORIES = new Set(['zero', 'one', 'two', 'few', 'many', 'other'])
/** `{ a: { b: 'x' } }` -> `{ 'a.b': 'x' }` (the registry is flat); a plural object (`{ one, other, ... }`) stays one entry. */
function flat(o, prefix = '', out = {}) {
  for (const [k, v] of Object.entries(o)) {
    if (v && typeof v === 'object' && Object.keys(v).every((c) => CATEGORIES.has(c))) out[`${prefix}${k}`] = v
    else if (v && typeof v === 'object') flat(v, `${prefix}${k}.`, out)
    else out[`${prefix}${k}`] = v
  }
  return out
}

