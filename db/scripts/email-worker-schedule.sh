#!/usr/bin/env bash
# email-worker-schedule.sh - turn the e-mail worker's SCHEDULER on / off on the LOCAL stack (m62, design 07 section 1.6).
#
#   bash db/scripts/email-worker-schedule.sh enable [--base-url URL]   # pg_cron every minute -> pg_net POST -> the email-worker function; stores the shared secret in Vault
#   bash db/scripts/email-worker-schedule.sh disable                   # removes both cron jobs, the Vault secret and the settings (back to the baseline)
#   bash db/scripts/email-worker-schedule.sh status                    # enabled?, the two cron jobs, the last three pg_net answers, the worker's last heartbeat
#   bash db/scripts/email-worker-schedule.sh kick                      # one POST now (the same thing "Send now" does); nothing happens when disabled
#
# Why a separate, explicit step: the migration schedules NOTHING by itself (a migration that starts sending mail on its own would be a surprise), and with the
# scheduler on, any queued row is delivered through whatever Google the function talks to (the FAKE one locally while ALLOW_FAKE_GOOGLE=1).
#
# Local wiring: the database container reaches the functions through Kong, http://kong:8000/functions/v1 (checked by `dev-functions.sh status`). The secret is
# EMAIL_WORKER_SECRET of local-db/functions.env (generated by `dev-functions.sh up`); it is fed to psql on STDIN (never on a command line) and never printed.
# PRODUCTION: set the same secret as a function secret (`supabase secrets set EMAIL_WORKER_SECRET=...`), deploy the function with --no-verify-jwt and run once in the SQL
# editor:  select app_private.email_worker_enable('https://<project-ref>.supabase.co/functions/v1', '<the secret>');   (see supabase-new/functions/email-worker/README.md).
set -euo pipefail
export MSYS_NO_PATHCONV=1

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
ENV_FILE="$ROOT/local-db/functions.env"
DB_CONTAINER="supabase_db_stack"
DEFAULT_BASE="http://kong:8000/functions/v1"

die() { printf 'error: %s\n' "$*" >&2; exit 1; }
envval() { [ -f "$ENV_FILE" ] || return 0; { grep -m1 -E "^$1=" "$ENV_FILE" || true; } | cut -d= -f2- | tr -d '\r'; }
psql_stdin() { docker exec -i "$DB_CONTAINER" psql -U postgres -d postgres -X -At -v ON_ERROR_STOP=1; }

command -v docker >/dev/null 2>&1 || die "docker is not on the PATH (is Docker Desktop running?)"
[ "$(docker inspect -f '{{.State.Running}}' "$DB_CONTAINER" 2>/dev/null || echo false)" = "true" ] || die "the local stack is not running ($DB_CONTAINER)"
# the function must exist in the database for the status / enable calls (m62 applied)
if [ "$(printf "select to_regprocedure('app_private.email_worker_enable(text,text)') is not null;" | psql_stdin)" != "t" ]; then
  die "m62 is not applied: docker exec -i $DB_CONTAINER psql -U postgres -d postgres -v ON_ERROR_STOP=1 < db/migrations/m62_email_worker.sql"
fi

sub="${1:-}"; [ $# -gt 0 ] && shift || true
case "$sub" in
  enable)
    base="$DEFAULT_BASE"
    while [ $# -gt 0 ]; do
      case "$1" in
        --base-url) [ $# -ge 2 ] || die "--base-url needs a value"; base="$2"; shift 2 ;;
        *) die "unknown option: $1" ;;
      esac
    done
    secret="$(envval EMAIL_WORKER_SECRET)"
    [ -n "$secret" ] || die "EMAIL_WORKER_SECRET is not in local-db/functions.env: run 'bash db/scripts/dev-functions.sh up' first (it adds it and restarts the runtime)"
    [ "${#secret}" -ge 24 ] || die "EMAIL_WORKER_SECRET is shorter than 24 characters"
    case "$secret" in *[!A-Za-z0-9_-]*) die "EMAIL_WORKER_SECRET holds a character other than A-Z a-z 0-9 - _ (the generated one never does)" ;; esac
    case "$base" in http://*|https://*) ;; *) die "--base-url must start with http:// or https://" ;; esac
    printf "select jsonb_pretty(app_private.email_worker_enable('%s', '%s'));\n" "$base" "$secret" | psql_stdin
    echo "scheduler enabled: pg_cron calls $base/email-worker every minute. Turn it off with: bash db/scripts/email-worker-schedule.sh disable"
    ;;
  disable)
    printf "select jsonb_pretty(app_private.email_worker_disable());\n" | psql_stdin
    echo "scheduler disabled (no cron job, no Vault secret, no settings)."
    ;;
  status)
    # one plain-language verdict first (like `dev-functions.sh status`), then the raw JSON for whoever needs the detail
    printf "select 'scheduler: ' || case when coalesce((s->>'enabled')::boolean, false) and jsonb_array_length(coalesce(s->'cron_jobs', '[]'::jsonb)) > 0 then 'ON' else 'OFF' end
         || ' | secret: ' || case when coalesce((s->>'secret_set')::boolean, false) then 'set' else 'not set' end
         || ' | cron jobs: ' || jsonb_array_length(coalesce(s->'cron_jobs', '[]'::jsonb))
         || ' | worker last ran: ' || coalesce(to_char((s->>'last_run_at')::timestamptz at time zone 'utc', 'YYYY-MM-DD HH24:MI') || ' UTC', 'never')
         || case when coalesce((s->>'enabled')::boolean, false) then '' else ' | nothing is sent by itself (run: email-worker-schedule.sh enable)' end
         from (select app_private.email_worker_status() s) x;\n" | psql_stdin
    printf "select jsonb_pretty(app_private.email_worker_status());\n" | psql_stdin
    ;;
  kick)
    r="$(printf "select coalesce(app_private.email_kick_worker()::text, 'not kicked (disabled, throttled or not configured)');\n" | psql_stdin)"
    echo "pg_net request: $r"
    ;;
  ""|-h|--help|help) sed -n '2,18p' "${BASH_SOURCE[0]}" ;;
  *) die "unknown command: $sub (enable | disable | status | kick)" ;;
esac
