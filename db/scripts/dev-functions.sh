#!/usr/bin/env bash
# dev-functions.sh - run the edge functions of supabase-new/functions on the LOCAL Supabase stack (its Edge Runtime), with a FAKE Google.
#
#   bash db/scripts/dev-functions.sh up [--app-url URL] [--no-sync]   # sync the sources, (generate local-db/functions.env), start the fake
#                                                                     #   Google (when the env file says ALLOW_FAKE_GOOGLE=1) and `functions serve`
#   bash db/scripts/dev-functions.sh down                             # stop both (the stack itself keeps running)
#   bash db/scripts/dev-functions.sh restart [--app-url URL]
#   bash db/scripts/dev-functions.sh status                           # what runs, what answers, which env NAMES are set (never a value)
#   bash db/scripts/dev-functions.sh logs [fake|functions|edge] [-f] [-n N]
#
# Prerequisite: the local stack runs WITH the edge runtime (local-db/README.md):
#     cd local-db/stack && npx supabase start -x logflare,vector,imgproxy,mailpit
# Files (all under the git-ignored local-db/):
#     functions.env            the secrets / settings of the functions (generated once; names + how to change them: db/README.md)
#     run/*.pid, logs/fake-google.log, logs/functions-serve.log
# Nothing here ever calls a real Google endpoint while ALLOW_FAKE_GOOGLE=1 (the default of the generated file): the OAuth, token, revoke and
# Gmail / Calendar addresses all point at db/scripts/fake-google/server.mjs on this machine. To use the REAL Google see db/README.md.
set -euo pipefail
export MSYS_NO_PATHCONV=1

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
LOCAL_DB="$ROOT/local-db"
STACK_DIR="$LOCAL_DB/stack"
ENV_FILE="$LOCAL_DB/functions.env"
RUN_DIR="$LOCAL_DB/run"
LOG_DIR="$LOCAL_DB/logs"
FAKE_PID="$RUN_DIR/fake-google.pid"
SERVE_PID="$RUN_DIR/functions-serve.pid"
SERVE_ENVSUM="$RUN_DIR/functions-serve.envsum"
FAKE_LOG="$LOG_DIR/fake-google.log"
SERVE_LOG="$LOG_DIR/functions-serve.log"
FAKE_PORT="${FAKE_GOOGLE_PORT:-54399}"
FAKE_HOST="${FAKE_GOOGLE_HOST:-127.0.0.1}"
API_URL="${SUPABASE_API_URL:-http://127.0.0.1:54321}"
DEFAULT_APP_URL="http://127.0.0.1:5174"
EDGE_CONTAINER="supabase_edge_runtime_stack"
KONG_CONTAINER="supabase_kong_stack"
DB_CONTAINER="supabase_db_stack"

say() { printf '%s\n' "$*"; }
die() { printf 'error: %s\n' "$*" >&2; exit 1; }
is_windows() { case "$(uname -s 2>/dev/null)" in MINGW*|MSYS*|CYGWIN*) return 0 ;; *) return 1 ;; esac; }
winpath() { if command -v cygpath >/dev/null 2>&1; then cygpath -m "$1"; else printf '%s' "$1"; fi; }

# ---------------------------------------------------------------------------------------------------------------- env file helpers
# NAME -> value (empty when absent). The values are only ever used, never printed.
envval() { [ -f "$ENV_FILE" ] || return 0; { grep -m1 -E "^$1=" "$ENV_FILE" || true; } | cut -d= -f2- | tr -d '\r'; }
has_env() { [ -n "$(envval "$1")" ]; }
set_envval() { # NAME VALUE: replace the line or append it
  local name="$1" value="$2" tmp="$ENV_FILE.tmp.$$"
  if grep -q -E "^$name=" "$ENV_FILE"; then
    awk -v n="$name" -v v="$value" 'BEGIN { p = n "=" } index($0, p) == 1 { print p v; next } { print }' "$ENV_FILE" > "$tmp"
  else
    { cat "$ENV_FILE"; printf '%s=%s\n' "$name" "$value"; } > "$tmp"
  fi
  mv "$tmp" "$ENV_FILE"
}
env_sum() { [ -f "$ENV_FILE" ] && cksum < "$ENV_FILE" | cut -d' ' -f1,2 || echo none; }
fake_mode() { [ "$(envval ALLOW_FAKE_GOOGLE)" = "1" ]; }
rand_b64u() { node -e "process.stdout.write(require('crypto').randomBytes(32).toString('base64url'))"; }
rand_hex() { node -e "process.stdout.write(require('crypto').randomBytes(${1:-32}).toString('hex'))"; }

ensure_env_file() {
  if [ -f "$ENV_FILE" ]; then return 0; fi
  command -v node >/dev/null 2>&1 || die "node is needed to generate the random secrets"
  mkdir -p "$LOCAL_DB"
  local state enc fsecret
  state="$(rand_b64u)"; enc="$(rand_hex 32)"; fsecret="fake-secret-$(rand_hex 16)"
  umask 077
  cat > "$ENV_FILE" <<EOF
# local-db/functions.env  (git-ignored, generated by db/scripts/dev-functions.sh on $(date +%Y-%m-%d); read by \`supabase functions serve --env-file\`)
# NEVER commit it, never paste a value into a chat or a ticket. Names and the meaning of every line: db/README.md ("Edge functions on the local stack")
# and docs/design/10-google-integration-setup.md. SUPABASE_URL / SUPABASE_ANON_KEY / SUPABASE_SERVICE_ROLE_KEY / SUPABASE_DB_URL are injected
# by the runtime and must NOT be set here.

# --- OAuth client (the FAKE Google accepts any values; for the real Google put the real client id / secret here) ---------------------
GOOGLE_CLIENT_ID=fake-client-id-local
GOOGLE_CLIENT_SECRET=$fsecret
# must equal the Authorised redirect URI of the client, character for character (the PUBLIC address of the function, through Kong)
GOOGLE_REDIRECT_URI=$API_URL/functions/v1/google-oauth-callback
# where the browser goes after Google: npm run dev:local serves http://127.0.0.1:5174 (\`dev-functions.sh up --app-url URL\` changes this line)
APP_URL=$DEFAULT_APP_URL
# generated once (>= 32 random characters); a NEW value on production, never this one
OAUTH_STATE_SECRET=$state

# --- token storage: 'auto' = Supabase Vault when the database has it (the local image does), else AES-256-GCM with TOKEN_ENC_KEY ---------
TOKEN_STORAGE=auto
# 64 hex characters, generated once (a spare while Vault is used; REQUIRED where Vault is missing). Keep a copy in the password manager.
TOKEN_ENC_KEY=$enc
TOKEN_ENC_KEY_OLD=

# --- policy (defaults shown) ---------------------------------------------------------------------------------------------------------
ALLOWED_GOOGLE_DOMAIN=athareg.com
SYSTEM_SENDER_EMAIL=startups@athareg.com
GOOGLE_PM_EMAIL_POLICY=same_email

# --- e-mail worker (m62): the shared secret between the database (pg_cron / pg_net) and the email-worker function; generated once -----------------
EMAIL_WORKER_SECRET=$(rand_b64u)

# --- FAKE GOOGLE (local tests only): DELETE these five lines to use the real Google (then db/scripts/dev-functions.sh will not start the fake) ---
# GOOGLE_AUTH_BASE is opened by the BROWSER (loopback); the other three are called by the function INSIDE the edge-runtime container (host.docker.internal).
ALLOW_FAKE_GOOGLE=1
GOOGLE_AUTH_BASE=http://127.0.0.1:$FAKE_PORT
GOOGLE_TOKEN_URL=http://host.docker.internal:$FAKE_PORT/token
GOOGLE_REVOKE_URL=http://host.docker.internal:$FAKE_PORT/revoke
GOOGLE_API_BASE=http://host.docker.internal:$FAKE_PORT
EOF
  say "created local-db/functions.env with freshly generated OAUTH_STATE_SECRET and TOKEN_ENC_KEY (values not shown) and the FAKE Google addresses"
}

# ---------------------------------------------------------------------------------------------------------------- process helpers
pid_of() { [ -f "$1" ] && cut -d' ' -f1 "$1" || true; }
winpid_of() { [ -f "$1" ] && cut -d' ' -f2 "$1" || true; }
alive() { local p; p="$(pid_of "$1")"; [ -n "$p" ] && kill -0 "$p" 2>/dev/null; }
record_pid() { # PIDFILE MSYSPID -> "pid winpid"
  local w=""
  [ -r "/proc/$2/winpid" ] && w="$(cat "/proc/$2/winpid" 2>/dev/null || true)"
  printf '%s %s\n' "$2" "${w:-$2}" > "$1"
}
kill_tree() { # PIDFILE: stops the process tree ONLY while the recorded process still exists (a stale pid file never kills a stranger)
  [ -f "$1" ] || return 0
  if alive "$1"; then
    local p w; p="$(pid_of "$1")"; w="$(winpid_of "$1")"
    if is_windows && [ -n "$w" ] && command -v taskkill >/dev/null 2>&1; then
      taskkill /PID "$w" /T /F >/dev/null 2>&1 || true
    fi
    kill "$p" 2>/dev/null || true
  fi
  rm -f "$1"
}
# Stops every process whose command line matches a PowerShell -like pattern (Windows) / pkill -f pattern (elsewhere). The pid file is not enough for
# `functions serve`: npx -> node -> supabase.exe is a chain of processes and the link between them can break, leaving an orphan that would
# keep a SECOND copy of the runtime logic alive. The pattern is specific to this script's own command line (the env file path).
kill_by_cmdline() { # WINDOWS_LIKE_PATTERN POSIX_REGEX
  if is_windows && command -v powershell.exe >/dev/null 2>&1; then
    # the pattern travels in an environment variable: the PowerShell command text (single-quoted here) never contains it, so it cannot match itself
    CMDLINE_LIKE="$1" powershell.exe -NoProfile -NonInteractive -Command '$p = $env:CMDLINE_LIKE; Get-CimInstance Win32_Process | Where-Object { ($_.Name -eq "node.exe" -or $_.Name -eq "supabase.exe") -and $_.CommandLine -like $p -and $_.ProcessId -ne $PID } | ForEach-Object { Stop-Process -Id $_.ProcessId -Force -ErrorAction SilentlyContinue }' >/dev/null 2>&1 || true
  elif command -v pkill >/dev/null 2>&1; then
    pkill -f "$2" >/dev/null 2>&1 || true
  fi
}
count_by_cmdline() { # WINDOWS_LIKE_PATTERN POSIX_REGEX -> number of matching processes
  if is_windows && command -v powershell.exe >/dev/null 2>&1; then
    CMDLINE_LIKE="$1" powershell.exe -NoProfile -NonInteractive -Command '$p = $env:CMDLINE_LIKE; @(Get-CimInstance Win32_Process | Where-Object { ($_.Name -eq "node.exe" -or $_.Name -eq "supabase.exe") -and $_.CommandLine -like $p -and $_.ProcessId -ne $PID }).Count' 2>/dev/null | tr -d '\r' | head -n1
  else
    pgrep -fc "$2" 2>/dev/null || echo 0
  fi
}
SERVE_LIKE='*functions serve --env-file*local-db/functions.env*'
SERVE_RE='functions serve --env-file.*local-db/functions.env'

http_code() { curl -s -o /dev/null -m "${2:-6}" -w '%{http_code}' "${@:3}" "$1" 2>/dev/null || true; }
anon_key() { [ -f "$ROOT/web/.env.local" ] && { grep -m1 '^VITE_SUPABASE_ANON_KEY=' "$ROOT/web/.env.local" || true; } | cut -d= -f2- | tr -d '\r"' || true; }
container_running() { [ "$(docker inspect -f '{{.State.Running}}' "$1" 2>/dev/null || echo false)" = "true" ]; }

need_stack() {
  command -v docker >/dev/null 2>&1 || die "docker is not on the PATH (is Docker Desktop running?)"
  container_running "$DB_CONTAINER" || die "the local stack is not running ($DB_CONTAINER). Start it: cd local-db/stack && npx supabase start -x logflare,vector,imgproxy,mailpit"
  container_running "$KONG_CONTAINER" || die "$KONG_CONTAINER is not running: restart the stack (cd local-db/stack && npx supabase stop && npx supabase start -x logflare,vector,imgproxy,mailpit)"
  # Kong only routes /functions/v1 when the stack was started WITHOUT excluding edge-runtime
  if ! docker image ls --format '{{.Repository}}' | grep -q 'edge-runtime'; then
    die "the edge-runtime image is not on this machine: start the stack once WITHOUT '-x edge-runtime' (see local-db/README.md)"
  fi
}

# ---------------------------------------------------------------------------------------------------------------- fake Google
fake_health() { [ "$(http_code "http://127.0.0.1:$FAKE_PORT/__health" 3)" = "200" ]; }
start_fake() {
  if ! fake_mode; then say "fake Google: not used (ALLOW_FAKE_GOOGLE is not 1 in functions.env: the functions will talk to the REAL Google)"; return 0; fi
  if alive "$FAKE_PID" && fake_health; then say "fake Google: already running on port $FAKE_PORT (pid $(pid_of "$FAKE_PID"))"; return 0; fi
  [ -f "$FAKE_PID" ] && kill_tree "$FAKE_PID"
  if fake_health; then die "port $FAKE_PORT already answers like a fake Google that this script did not start: stop it (or set FAKE_GOOGLE_PORT)"; fi
  mkdir -p "$RUN_DIR" "$LOG_DIR"
  local server; server="$(winpath "$ROOT/db/scripts/fake-google/server.mjs")"
  : > "$FAKE_LOG"
  # the client id / secret / redirect URI come from the same env file as the functions' (the fake enforces them like Google would)
  FAKE_GOOGLE_CLIENT_ID="$(envval GOOGLE_CLIENT_ID)" FAKE_GOOGLE_CLIENT_SECRET="$(envval GOOGLE_CLIENT_SECRET)" \
  FAKE_GOOGLE_REDIRECT_URIS="$(envval GOOGLE_REDIRECT_URI)" FAKE_GOOGLE_PORT="$FAKE_PORT" FAKE_GOOGLE_HOST="$FAKE_HOST" \
    node "$server" >> "$FAKE_LOG" 2>&1 &
  local pid=$!
  disown "$pid" 2>/dev/null || true
  record_pid "$FAKE_PID" "$pid"
  local i
  for i in $(seq 1 30); do fake_health && break; sleep 0.5; done
  fake_health || { tail -n 20 "$FAKE_LOG" >&2 || true; die "the fake Google did not start (log: local-db/logs/fake-google.log)"; }
  say "fake Google: running on http://$FAKE_HOST:$FAKE_PORT (pid $pid; log local-db/logs/fake-google.log)"
}
stop_fake() {
  if [ -f "$FAKE_PID" ]; then kill_tree "$FAKE_PID"; say "fake Google: stopped"; else say "fake Google: was not started by this script"; fi
}

# ---------------------------------------------------------------------------------------------------------------- functions serve
serve_ready() { # hello-world needs a JWT (the anon key is enough) and must report OUR env file as loaded: the stack's own edge runtime
  local k body  # (started by `supabase start`, without the env file) answers 200 too, so a plain 200 would be a false "ready"
  k="$(anon_key)"
  body="$(curl -s -m 8 "$API_URL/functions/v1/hello-world" -H "apikey: $k" -H "Authorization: Bearer $k" 2>/dev/null || true)"
  case "$body" in *'"OAUTH_STATE_SECRET":true'*) return 0 ;; *) return 1 ;; esac
}
start_serve() {
  if alive "$SERVE_PID"; then
    if [ "$(cat "$SERVE_ENVSUM" 2>/dev/null || true)" = "$(env_sum)" ]; then say "functions: already served (pid $(pid_of "$SERVE_PID"))"; return 0; fi
    say "functions: functions.env changed since the last start: restarting the runtime"
    stop_serve
  fi
  [ -f "$SERVE_PID" ] && kill_tree "$SERVE_PID"
  mkdir -p "$RUN_DIR" "$LOG_DIR"
  : > "$SERVE_LOG"
  local envfile; envfile="$(winpath "$ENV_FILE")"
  ( cd "$STACK_DIR" && exec npx supabase functions serve --env-file "$envfile" ) >> "$SERVE_LOG" 2>&1 &
  local pid=$!
  disown "$pid" 2>/dev/null || true
  record_pid "$SERVE_PID" "$pid"
  env_sum > "$SERVE_ENVSUM"
  say "functions: starting the edge runtime (pid $pid; the first start downloads supabase-js into the runtime cache, up to a few minutes)"
  local i
  for i in $(seq 1 120); do
    serve_ready && { say "functions: serving at $API_URL/functions/v1/<name>"; return 0; }
    alive "$SERVE_PID" || { tail -n 25 "$SERVE_LOG" >&2 || true; die "the functions server stopped (log: local-db/logs/functions-serve.log)"; }
    sleep 2
  done
  tail -n 25 "$SERVE_LOG" >&2 || true
  local code; code="$(http_code "$API_URL/functions/v1/hello-world" 8 -H "apikey: $(anon_key)")"
  [ "$code" = "404" ] && say "Kong answers 404 for /functions/v1: the stack was started with '-x edge-runtime'. Restart it without that flag (db/README.md, Troubleshooting)." >&2
  die "the functions did not answer within 4 minutes (log: local-db/logs/functions-serve.log; see 'Troubleshooting' in db/README.md)"
}
stop_serve() {
  local was=0
  alive "$SERVE_PID" && was=1
  kill_tree "$SERVE_PID"; rm -f "$SERVE_ENVSUM"
  if [ "$(count_by_cmdline "$SERVE_LIKE" "$SERVE_RE")" != "0" ]; then kill_by_cmdline "$SERVE_LIKE" "$SERVE_RE"; was=1; fi
  # the CLI normally removes its container when it exits; after a hard kill it may linger: remove it so the next start is clean
  if docker inspect "$EDGE_CONTAINER" >/dev/null 2>&1; then
    local i; for i in 1 2 3 4 5; do container_running "$EDGE_CONTAINER" || break; sleep 1; done
    docker rm -f "$EDGE_CONTAINER" >/dev/null 2>&1 || true
    was=1
  fi
  if [ "$was" = 1 ]; then say "functions: stopped (/functions/v1 has no upstream until the next 'up')"; else say "functions: were not running"; fi
}

# ---------------------------------------------------------------------------------------------------------------- commands
parse_up_args() {
  APP_URL_ARG=""; DO_SYNC=1
  while [ $# -gt 0 ]; do
    case "$1" in
      --app-url) [ $# -ge 2 ] || die "--app-url needs a value"; APP_URL_ARG="$2"; shift 2 ;;
      --no-sync) DO_SYNC=0; shift ;;
      *) die "unknown option: $1" ;;
    esac
  done
}

cmd_up() {
  parse_up_args "$@"
  need_stack
  [ "$DO_SYNC" = 1 ] && bash "$ROOT/db/scripts/sync-functions.sh" >/dev/null && say "functions: sources synced into local-db/stack/supabase/functions"
  ensure_env_file
  # m62: the shared secret the e-mail worker checks (database -> function over pg_net, or a script). Added to an env file that predates it; the file change restarts the runtime.
  if ! has_env EMAIL_WORKER_SECRET; then
    set_envval EMAIL_WORKER_SECRET "$(rand_b64u)"
    say "added EMAIL_WORKER_SECRET to local-db/functions.env (value not shown)"
  fi
  if [ -n "$APP_URL_ARG" ]; then
    case "$APP_URL_ARG" in http://127.0.0.1:*|http://localhost:*|https://*) ;; *) die "--app-url must be http://127.0.0.1:<port> or an https:// address" ;; esac
    set_envval APP_URL "${APP_URL_ARG%/}"
    say "APP_URL set to ${APP_URL_ARG%/} in local-db/functions.env"
  fi
  # the real Google must never be called with the placeholder client of the generated file
  if ! fake_mode; then
    case "$(envval GOOGLE_CLIENT_ID)" in ""|fake-*) die "ALLOW_FAKE_GOOGLE is not set and GOOGLE_CLIENT_ID is empty or a placeholder: put the real client id / secret in local-db/functions.env first" ;; esac
  fi
  start_fake
  start_serve
  say ""
  say "ready. Try: bash db/scripts/dev-functions.sh status"
}
cmd_down() { stop_serve; stop_fake; }
cmd_restart() { cmd_down; cmd_up "$@"; }

cmd_status() {
  local ok=0 bad=0
  chk() { # LABEL ok|bad DETAIL
    if [ "$2" = ok ]; then printf '  [ ok ] %-34s %s\n' "$1" "${3:-}"; else printf '  [FAIL] %-34s %s\n' "$1" "${3:-}"; bad=$((bad+1)); fi
  }
  say "stack"
  if container_running "$DB_CONTAINER"; then chk "database container" ok "$DB_CONTAINER"; else chk "database container" bad "not running"; fi
  if container_running "$KONG_CONTAINER"; then chk "gateway (Kong)" ok "$API_URL"; else chk "gateway (Kong)" bad "not running"; fi
  if docker image ls --format '{{.Repository}}' 2>/dev/null | grep -q 'edge-runtime'; then chk "edge-runtime image" ok "present"; else chk "edge-runtime image" bad "missing: start the stack without '-x edge-runtime'"; fi
  if container_running "$EDGE_CONTAINER"; then chk "edge runtime container" ok "$EDGE_CONTAINER"; else chk "edge runtime container" bad "not running (db/scripts/dev-functions.sh up)"; fi

  say "functions.env (names only)"
  if [ ! -f "$ENV_FILE" ]; then
    chk "local-db/functions.env" bad "missing: 'up' creates it"
  else
    chk "local-db/functions.env" ok "present"
    local n
    for n in GOOGLE_CLIENT_ID GOOGLE_CLIENT_SECRET GOOGLE_REDIRECT_URI APP_URL OAUTH_STATE_SECRET; do
      if has_env "$n"; then chk "$n" ok "set"; else chk "$n" bad "MISSING"; fi
    done
    if has_env EMAIL_WORKER_SECRET; then chk "EMAIL_WORKER_SECRET" ok "set"; else chk "EMAIL_WORKER_SECRET" bad "MISSING (m62 e-mail worker): 'up' adds it"; fi
    local st; st="$(envval OAUTH_STATE_SECRET)"
    if [ "${#st}" -ge 32 ]; then chk "OAUTH_STATE_SECRET length" ok ">= 32"; else chk "OAUTH_STATE_SECRET length" bad "shorter than 32"; fi
    local mode="$(envval TOKEN_STORAGE)"; mode="${mode:-auto}"
    if [ "$mode" = "aes" ] || [ "$mode" = "auto" ]; then
      if has_env TOKEN_ENC_KEY; then
        local k; k="$(envval TOKEN_ENC_KEY)"
        if [ "${#k}" -eq 64 ]; then chk "TOKEN_ENC_KEY" ok "set (64 hex)"; else chk "TOKEN_ENC_KEY" bad "must be 64 hex characters"; fi
      elif [ "$mode" = "aes" ]; then chk "TOKEN_ENC_KEY" bad "MISSING (TOKEN_STORAGE=aes)"; else chk "TOKEN_ENC_KEY" ok "not set (Vault is used)"; fi
    fi
    say "  token storage setting     : $mode"
    say "  redirect URI              : $(envval GOOGLE_REDIRECT_URI)"
    say "  app URL                   : $(envval APP_URL)"
    if fake_mode; then say "  Google                    : FAKE Google (ALLOW_FAKE_GOOGLE=1): no real Google call is possible"
    else
      say "  Google                    : REAL Google (no ALLOW_FAKE_GOOGLE)"
      local o left=""
      for o in GOOGLE_AUTH_BASE GOOGLE_TOKEN_URL GOOGLE_REVOKE_URL GOOGLE_API_BASE; do has_env "$o" && left="$left $o"; done
      if [ -n "$left" ]; then chk "leftover fake addresses" bad "remove$left from functions.env (the functions refuse to start with them)"; fi
      case "$(envval GOOGLE_CLIENT_ID)" in ""|fake-*) chk "real client id" bad "GOOGLE_CLIENT_ID is empty or still the placeholder" ;; esac
    fi
  fi

  say "fake Google"
  if fake_mode; then
    if fake_health; then chk "fake server" ok "port $FAKE_PORT$(alive "$FAKE_PID" && printf ', pid %s' "$(pid_of "$FAKE_PID")" || printf ', not started by this script')"; else chk "fake server" bad "not answering on port $FAKE_PORT (up)"; fi
    if container_running "$DB_CONTAINER" && fake_health; then
      if docker exec "$DB_CONTAINER" bash -c "exec 3<>/dev/tcp/host.docker.internal/$FAKE_PORT" >/dev/null 2>&1; then chk "reachable from containers" ok "host.docker.internal:$FAKE_PORT"; else chk "reachable from containers" bad "host.docker.internal:$FAKE_PORT (try FAKE_GOOGLE_HOST=0.0.0.0, see Troubleshooting)"; fi
    fi
  else
    say "  (not used in this mode)"
  fi

  say "functions"
  if alive "$SERVE_PID"; then chk "functions serve process" ok "pid $(pid_of "$SERVE_PID")"; else chk "functions serve process" bad "not started by this script"; fi
  local procs; procs="$(count_by_cmdline "$SERVE_LIKE" "$SERVE_RE")"
  case "$procs" in ""|0|1|2) : ;; *) chk "one copy of functions serve" bad "$procs matching processes: run 'down' then 'up'" ;; esac
  if [ -f "$SERVE_ENVSUM" ] && [ "$(cat "$SERVE_ENVSUM")" != "$(env_sum)" ]; then chk "env file up to date" bad "functions.env changed after the start: restart"; fi
  local k code; k="$(anon_key)"
  code="$(http_code "$API_URL/functions/v1/hello-world?db=1" 8 -H "apikey: $k" -H "Authorization: Bearer $k")"
  if [ "$code" = "200" ]; then chk "hello-world (+ database round trip)" ok "HTTP 200"; else chk "hello-world" bad "HTTP ${code:-none}"; fi
  code="$(http_code "$API_URL/functions/v1/hello-world" 8)"
  if [ "$code" = "401" ]; then chk "JWT check on (no token)" ok "HTTP 401"; else chk "JWT check on (no token)" bad "HTTP ${code:-none} (expected 401)"; fi
  code="$(http_code "$API_URL/functions/v1/google-oauth-start" 8 -X POST -H 'Content-Type: application/json' -d '{}')"
  if [ "$code" = "401" ]; then chk "google-oauth-start needs a login" ok "HTTP 401"; else chk "google-oauth-start needs a login" bad "HTTP ${code:-none} (expected 401)"; fi
  code="$(http_code "$API_URL/functions/v1/google-oauth-callback" 8)"
  case "$code" in 302|303|400) chk "google-oauth-callback is public" ok "HTTP $code (no login needed)" ;; *) chk "google-oauth-callback is public" bad "HTTP ${code:-none} (expected 302)" ;; esac
  say ""
  if [ "$bad" -eq 0 ]; then say "all good."; else say "$bad check(s) failed (db/README.md, section 'Troubleshooting')."; return 1; fi
}

cmd_logs() {
  local which="functions" follow="" lines=60
  while [ $# -gt 0 ]; do
    case "$1" in
      fake|functions|edge) which="$1"; shift ;;
      -f) follow="-f"; shift ;;
      -n) [ $# -ge 2 ] || die "-n needs a number"; lines="$2"; shift 2 ;;
      *) die "unknown option: $1" ;;
    esac
  done
  case "$which" in
    fake) [ -f "$FAKE_LOG" ] || die "no log yet: $FAKE_LOG"; tail -n "$lines" ${follow:+-f} "$FAKE_LOG" ;;
    functions) [ -f "$SERVE_LOG" ] || die "no log yet: $SERVE_LOG"; tail -n "$lines" ${follow:+-f} "$SERVE_LOG" ;;
    edge) docker logs --tail "$lines" ${follow:+-f} "$EDGE_CONTAINER" ;;
  esac
}

sub="${1:-}"; [ $# -gt 0 ] && shift || true
case "$sub" in
  up) cmd_up "$@" ;;
  down) cmd_down ;;
  restart) cmd_restart "$@" ;;
  status) cmd_status ;;
  logs) cmd_logs "$@" ;;
  ""|-h|--help|help) sed -n '2,16p' "${BASH_SOURCE[0]}" ;;
  *) die "unknown command: $sub (up | down | restart | status | logs)" ;;
esac
